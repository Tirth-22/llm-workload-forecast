"""
Module 20 — Forecast-to-Control Comparison

Research topic:
Short-Term LLM Workload Prediction for Adaptive Cloud Computing

Purpose
-------
Determine whether the choice of short-term workload forecaster changes
downstream adaptive capacity-control performance.

Primary forecasting models:
    1. Persistence
    2. HGB
    3. CP-HGB

Important:
- Reuses the exact locked-test predictions produced by Module 19.
- Does not retrain HGB or CP-HGB.
- Does not tune parameters on the locked test set.
- Does not introduce a new risk model or change-point detector.
- Uses a fixed 10% capacity reserve to isolate the effect of forecasting.
- This is a normalized workload-capacity experiment; it does NOT claim
  a direct token-to-GPU conversion.

Input
-----
results/predictions/baseline_forecast_predictions.csv

Actual Module 19 columns:
    interval
    actual_next_5min_tokens
    persistence_prediction
    seasonal_naive_prediction
    moving_average_prediction
    Linear Regression
    Random Forest
    hgb_prediction
    cp_hgb_prediction

Outputs
-------
results/policies/module20_forecast_control_comparison.csv
results/tables/module20_forecast_control_metrics.csv
results/validation/module20_metadata.json
"""

from pathlib import Path
import json

import numpy as np
import pandas as pd


ROOT = Path(__file__).resolve().parents[1]

INPUT = (
    ROOT
    / "results"
    / "predictions"
    / "baseline_forecast_predictions.csv"
)

POLICY_DIR = ROOT / "results" / "policies"
TABLE_DIR = ROOT / "results" / "tables"
VALIDATION_DIR = ROOT / "results" / "validation"

POLICY_DIR.mkdir(parents=True, exist_ok=True)
TABLE_DIR.mkdir(parents=True, exist_ok=True)
VALIDATION_DIR.mkdir(parents=True, exist_ok=True)


# ----------------------------------------------------------------------
# FIXED CONTROL ASSUMPTIONS
# ----------------------------------------------------------------------

# This experiment deliberately does not optimize these values on test data.
RESERVE_FRACTION = 0.10


# ----------------------------------------------------------------------
# ACTUAL MODULE 19 COLUMN NAMES
# ----------------------------------------------------------------------

PRIMARY_FORECAST_COLUMNS = {
    "Persistence": "persistence_prediction",
    "HGB": "hgb_prediction",
    "CP-HGB": "cp_hgb_prediction",
}


# ----------------------------------------------------------------------
# INPUT VALIDATION
# ----------------------------------------------------------------------

def validate_input(df):
    """Validate the exact output schema produced by Module 19."""

    required = {
        "interval",
        "actual_next_5min_tokens",
        *PRIMARY_FORECAST_COLUMNS.values(),
    }

    missing = sorted(required - set(df.columns))

    if missing:
        raise ValueError(
            "Module 19 prediction file is missing required columns:\n"
            + "\n".join(f"  - {column}" for column in missing)
        )

    test = df.copy()

    # Module 19's prediction file contains scored test rows.
    # It does not contain a 'split' column, so the entire file is treated
    # as the locked-test prediction output generated by Module 19.
    if test.empty:
        raise ValueError(
            "Module 19 prediction file contains no rows."
        )

    test = test.sort_values("interval").reset_index(drop=True)

    if test["actual_next_5min_tokens"].isna().any():
        raise ValueError(
            "Module 19 output contains rows with missing future targets."
        )

    intervals = test["interval"].astype(int).to_numpy()

    if not np.all(np.diff(intervals) > 0):
        raise ValueError(
            "Module 19 intervals are not strictly increasing."
        )

    for model, column in PRIMARY_FORECAST_COLUMNS.items():

        values = test[column].astype(float).to_numpy()

        if not np.isfinite(values).all():
            raise ValueError(
                f"{model} contains non-finite predictions."
            )

        if (values < 0).any():
            raise ValueError(
                f"{model} contains negative predictions."
            )

    return test


# ----------------------------------------------------------------------
# FORECAST → CAPACITY CONTROL
# ----------------------------------------------------------------------

def control_simulation(actual, forecast):
    """
    Apply the same fixed normalized-capacity controller to every forecast.

    Provisioned capacity = forecast * (1 + fixed reserve).

    Because the controller is identical for all forecasting models,
    differences in downstream metrics are attributable to the forecasts
    rather than model-specific controller tuning.
    """

    provisioned = forecast * (1.0 + RESERVE_FRACTION)

    shortage = np.maximum(
        actual - provisioned,
        0.0,
    )

    unused = np.maximum(
        provisioned - actual,
        0.0,
    )

    p95 = float(
        np.percentile(shortage, 95)
    )

    tail = shortage[shortage >= p95]

    cvar95 = (
        float(np.mean(tail))
        if len(tail) > 0
        else 0.0
    )

    mean_actual = float(np.mean(actual))
    mean_provisioned = float(np.mean(provisioned))

    return {
        "under_provisioned_percent": float(
            np.mean(shortage > 0) * 100
        ),
        "mean_shortage": float(
            np.mean(shortage)
        ),
        "p95_shortage": p95,
        "cvar95_shortage": cvar95,
        "mean_unused_capacity": float(
            np.mean(unused)
        ),
        "mean_provisioned_capacity": mean_provisioned,
        "mean_actual_workload": mean_actual,
        "cost_index": (
            mean_provisioned / mean_actual
            if mean_actual > 0
            else np.nan
        ),
        "total_shortage": float(
            np.sum(shortage)
        ),
        "total_unused_capacity": float(
            np.sum(unused)
        ),
    }


# ----------------------------------------------------------------------
# MAIN
# ----------------------------------------------------------------------

def main():

    print("=" * 70)
    print("MODULE 20 — FORECAST-TO-CONTROL COMPARISON")
    print("=" * 70)

    print("\n[1] Loading Module 19 predictions...")

    if not INPUT.exists():
        raise FileNotFoundError(
            f"Module 19 prediction file not found:\n{INPUT}"
        )

    df = pd.read_csv(INPUT)

    print(
        f"Rows loaded: {len(df):,}"
    )

    print(
        f"Columns: {list(df.columns)}"
    )

    print(
        "\n[2] Validating exact Module 19 output schema..."
    )

    test = validate_input(df)

    print(
        "Input schema validation: PASS"
    )

    print(
        f"Locked-test prediction rows: {len(test):,}"
    )

    print(
        f"Interval range: "
        f"{int(test['interval'].min())} -> "
        f"{int(test['interval'].max())}"
    )

    actual = (
        test["actual_next_5min_tokens"]
        .astype(float)
        .to_numpy()
    )

    print(
        "\n[3] Running identical capacity controller "
        "for Persistence, HGB, and CP-HGB..."
    )

    policy_rows = []
    metrics_rows = []

    for model_name, forecast_column in PRIMARY_FORECAST_COLUMNS.items():

        forecast = (
            test[forecast_column]
            .astype(float)
            .to_numpy()
        )

        metrics = control_simulation(
            actual,
            forecast,
        )

        metrics["forecast_model"] = model_name
        metrics["forecast_column"] = forecast_column
        metrics["reserve_fraction"] = RESERVE_FRACTION

        metrics_rows.append(metrics)

        for index in range(len(test)):

            forecast_value = float(
                forecast[index]
            )

            provisioned = (
                forecast_value
                * (1.0 + RESERVE_FRACTION)
            )

            policy_rows.append({
                "interval": int(
                    test.loc[index, "interval"]
                ),
                "forecast_model": model_name,
                "actual_workload": float(
                    actual[index]
                ),
                "forecast_workload": forecast_value,
                "reserve_fraction": RESERVE_FRACTION,
                "provisioned_capacity": provisioned,
                "shortage": max(
                    float(actual[index])
                    - provisioned,
                    0.0,
                ),
                "unused_capacity": max(
                    provisioned
                    - float(actual[index]),
                    0.0,
                ),
            })

        print(
            f"\n{model_name}"
        )

        print(
            f"  Under-provisioned: "
            f"{metrics['under_provisioned_percent']:.4f}%"
        )

        print(
            f"  Mean shortage: "
            f"{metrics['mean_shortage']:.4f}"
        )

        print(
            f"  P95 shortage: "
            f"{metrics['p95_shortage']:.4f}"
        )

        print(
            f"  CVaR95 shortage: "
            f"{metrics['cvar95_shortage']:.4f}"
        )

        print(
            f"  Mean unused capacity: "
            f"{metrics['mean_unused_capacity']:.4f}"
        )

        print(
            f"  Mean provisioned capacity: "
            f"{metrics['mean_provisioned_capacity']:.4f}"
        )

        print(
            f"  Cost index: "
            f"{metrics['cost_index']:.6f}"
        )

    policy_df = pd.DataFrame(
        policy_rows
    )

    metrics_df = pd.DataFrame(
        metrics_rows
    )

    # Put model name first for readability.
    metrics_df = metrics_df[
        [
            "forecast_model",
            "forecast_column",
            "under_provisioned_percent",
            "mean_shortage",
            "p95_shortage",
            "cvar95_shortage",
            "mean_unused_capacity",
            "mean_provisioned_capacity",
            "mean_actual_workload",
            "cost_index",
            "total_shortage",
            "total_unused_capacity",
            "reserve_fraction",
        ]
    ]

    policy_path = (
        POLICY_DIR
        / "module20_forecast_control_comparison.csv"
    )

    metrics_path = (
        TABLE_DIR
        / "module20_forecast_control_metrics.csv"
    )

    metadata_path = (
        VALIDATION_DIR
        / "module20_metadata.json"
    )

    policy_df.to_csv(
        policy_path,
        index=False,
    )

    metrics_df.to_csv(
        metrics_path,
        index=False,
    )

    metadata = {
        "module": "20_forecast_to_control_comparison",
        "research_topic": (
            "Short-Term LLM Workload Prediction "
            "for Adaptive Cloud Computing"
        ),
        "input_file": str(INPUT),
        "input_schema_source": (
            "actual Module 19 output"
        ),
        "locked_test_only": True,
        "forecast_models_compared": [
            "Persistence",
            "HGB",
            "CP-HGB",
        ],
        "forecast_models_retrained": False,
        "controller_type": (
            "fixed normalized-capacity forecast controller"
        ),
        "reserve_fraction": RESERVE_FRACTION,
        "controller_parameters_tuned_on_test": False,
        "purpose": (
            "Determine whether the choice of short-term "
            "workload forecaster changes downstream "
            "capacity-control performance."
        ),
        "cloud_resource_interpretation": (
            "Normalized workload capacity only; "
            "no direct token-to-GPU conversion is claimed."
        ),
    }

    with open(
        metadata_path,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            metadata,
            file,
            indent=2,
        )

    print("\n" + "=" * 70)
    print("MODULE 20 RESULT")
    print("=" * 70)

    print(
        metrics_df[
            [
                "forecast_model",
                "under_provisioned_percent",
                "mean_shortage",
                "p95_shortage",
                "cvar95_shortage",
                "mean_unused_capacity",
                "mean_provisioned_capacity",
                "cost_index",
            ]
        ].to_string(index=False)
    )

    print("\nCreated:")
    print(f"  {policy_path}")
    print(f"  {metrics_path}")
    print(f"  {metadata_path}")

    print("\nNo model was retrained.")
    print("No locked-test parameter was optimized.")
    print("No forecasting model was declared superior.")
    print("MODULE 20 COMPLETE")


if __name__ == "__main__":
    main()
